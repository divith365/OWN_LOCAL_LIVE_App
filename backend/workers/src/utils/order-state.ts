import { OrderStatus } from '@ownlocal/types';

const VALID_TRANSITIONS: Record<OrderStatus, OrderStatus[]> = {
  CREATED: ['MERCHANT_CONFIRMATION_PENDING', 'CUSTOMER_CANCELLED', 'FAILED'],
  MERCHANT_CONFIRMATION_PENDING: [
    'MERCHANT_CONFIRMED',
    'MERCHANT_REJECTED',
    'CUSTOMER_CANCELLED',
    'PAYMENT_PENDING',
    'RIDER_ASSIGNMENT_PENDING',
  ],
  MERCHANT_CONFIRMED: [
    'RIDER_ASSIGNMENT_PENDING',
    'RIDER_ASSIGNED',
    'PAYMENT_PENDING',
    'PAYMENT_CONFIRMED',
    'PREPARING',
    'CUSTOMER_CANCELLED',
  ],
  RIDER_ASSIGNMENT_PENDING: [
    'RIDER_ASSIGNED',
    'PREPARING',
    'MERCHANT_REJECTED',
    'CUSTOMER_CANCELLED',
  ],
  RIDER_ASSIGNED: [
    'PREPARING',
    'READY_FOR_PICKUP',
    'RIDER_CANCELLED',
    'CUSTOMER_CANCELLED',
  ],
  PAYMENT_PENDING: [
    'PAYMENT_CONFIRMED',
    'PAYMENT_FAILED',
    'CUSTOMER_CANCELLED',
  ],
  PAYMENT_CONFIRMED: [
    'PREPARING',
    'RIDER_ASSIGNMENT_PENDING',
    'REFUND_PENDING',
  ],
  PREPARING: ['READY_FOR_PICKUP', 'REFUND_PENDING'],
  READY_FOR_PICKUP: ['PICKED_UP', 'REFUND_PENDING'],
  PICKED_UP: ['OUT_FOR_DELIVERY', 'REFUND_PENDING'],
  OUT_FOR_DELIVERY: ['DELIVERED', 'FAILED', 'REFUND_PENDING'],
  DELIVERED: ['REFUND_PENDING'],
  MERCHANT_REJECTED: ['REFUND_PENDING'],
  CUSTOMER_CANCELLED: ['REFUND_PENDING'],
  RIDER_CANCELLED: ['RIDER_ASSIGNMENT_PENDING', 'REFUND_PENDING'],
  PAYMENT_FAILED: [],
  REFUND_PENDING: ['REFUNDED'],
  REFUNDED: [],
  FAILED: ['REFUND_PENDING'],
};

export function isValidOrderTransition(
  currentStatus: OrderStatus,
  nextStatus: OrderStatus
): boolean {
  if (currentStatus === nextStatus) return true;
  const allowed = VALID_TRANSITIONS[currentStatus] || [];
  return allowed.includes(nextStatus);
}
